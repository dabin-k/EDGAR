def ground_truth_model(data: dict, params: dict, components: dict) -> jnp.ndarray:
    """Ground-truth growth model for a single plant (Liebig's law of the minimum).

    This is the per-sample model signature that discovered models should follow;
    `apply_model` vmaps it over plants and passes in the sub-components.

    Args:
        data: Dict with "L" (light) and "N" (nitrogen), each of shape (n_trials,).
        params: Dict of scalar per-plant parameters "K_L", "K_N" and "mu_max".
        components: Dict of fixed sub-component functions,
            `components["g_light"](L, K_L)` and `components["g_nitrogen"](N, K_N)`.

    Returns:
        Predicted growth rate, shape (n_trials,).
    """
    L = data["L"]
    N = data["N"]

    K_L = params["K_L"]
    K_N = params["K_N"]
    mu_max = params["mu_max"]

    g_light = components["g_light"]
    g_nitrogen = components["g_nitrogen"]

    return mu_max * jnp.minimum(g_light(L, K_L), g_nitrogen(N, K_N))


def simulate_growth(
    seed: int = 42,
    n_plants: int = 10,
    n_trials: int = 100,
    L_range: tuple[float, float] = (0.0, 1.0),
    N_range: tuple[float, float] = (1.0, 100.0),
    K_L_range: tuple[float, float] = (0.01, 0.2),
    K_N_range: tuple[float, float] = (1.0, 20.0),
    mu_max_range: tuple[float, float] = (1.0, 2.0),
) -> tuple[dict[str, np.ndarray], dict[str, np.ndarray]]:
    """Simulates noiseless plant growth rates from `ground_truth_model`.

    Each plant gets its own parameters (K_L, K_N, mu_max), and L, N are sampled
    independently per plant and time point.

    Args:
        seed: Random seed.
        n_plants: Number of plants (samples).
        n_trials: Number of time points per plant.
        L_range: Uniform sampling range for light.
        N_range: Uniform sampling range for nitrogen.
        K_L_range: Uniform sampling range for the per-plant light half-saturation.
        K_N_range: Uniform sampling range for the per-plant nitrogen half-saturation.
        mu_max_range: Uniform sampling range for the per-plant maximum growth rate.

    Returns:
        A tuple (data, true_params). `data` has keys "growth_rate", "L", "N",
        each of shape (n_plants, n_trials). `true_params` has keys "K_L", "K_N",
        "mu_max", each of shape (n_plants,).
    """
    rng = np.random.default_rng(seed)

    # Use float32 throughout to match JAX's default precision.
    true_params = {
        "K_L": rng.uniform(*K_L_range, n_plants).astype(np.float32),
        "K_N": rng.uniform(*K_N_range, n_plants).astype(np.float32),
        "mu_max": rng.uniform(*mu_max_range, n_plants).astype(np.float32),
    }
    L = rng.uniform(*L_range, (n_plants, n_trials)).astype(np.float32)
    N = rng.uniform(*N_range, (n_plants, n_trials)).astype(np.float32)

    growth_rate = np.asarray(
        apply_model(ground_truth_model, {"L": L, "N": N}, true_params)
    )
    return {"growth_rate": growth_rate, "L": L, "N": N}, true_params


def load_data(
    data_path: str = "",
    seed: int = 42,
    n_plants: int = 10,
    n_trials: int = 100,
    n_eval_samples: int = 2,
):
    """Simulates plant growth data, then splits it into discovery, validation, and evaluation sets.

    Data are generated by `simulate_growth` (noiseless). One plant is one sample
    and one time point is one trial. Plants are split 50/50 into `discover` /
    `validate`, and time points are split 50/50 into train / test within each.

    Args:
        data_path (str): Unused; data are simulated.
        seed (int): Random seed for simulation and splitting.
        n_plants (int): Number of plants (samples) to simulate.
        n_trials (int): Number of time points per plant.
        n_eval_samples (int): The number of samples to use for generating the
            evaluation fingerprint, which is used for deduplication.

    Returns:
        tuple: A tuple containing (X_discover, X_validate, X_eval).

            - **X_discover** (tuple): Contains `X_disc_train` and `X_disc_test`.
                - `X_disc_train` (dict): A dictionary of numpy arrays, typically
                  with shape `(n_samples_discover_train, n_trials)`. This data
                  is exposed to the LLM during the model discovery phase.
                - `X_disc_test` (dict): A dictionary of numpy arrays, typically
                  with shape `(n_samples_discover_test, n_trials)`. This is a
                  held-out test set used within the discovery phase for scoring
                  and feedback.
            - **X_validate** (tuple): Contains `X_val_train` and `X_val_test`.
                - `X_val_train` (dict): A dictionary of numpy arrays, typically
                  with shape `(n_samples_validate_train, n_trials)`. This data
                  is never seen during the discovery phase and is reserved for
                  final model validation.
                - `X_val_test` (dict): A dictionary of numpy arrays, typically
                  with shape `(n_samples_validate_test, n_trials)`. This is a
                  final held-out evaluation set for robust performance assessment.
            - **X_eval** (dict): A small subset of data from `X_disc_train` used
              for generating model fingerprints for deduplication. It contains numpy
              arrays plus `_sample_indices` (a NumPy integer array indicating
              positions within `disc_idx`).
    """
    X, _ = simulate_growth(seed=seed, n_plants=n_plants, n_trials=n_trials)

    # ── split plants 50/50 into discover / validate ──
    # Use seed+1 to decouple splitting from data generation
    rng = np.random.default_rng(seed + 1)

    perm_s = rng.permutation(n_plants)
    disc_idx = np.sort(perm_s[: n_plants // 2])
    val_idx = np.sort(perm_s[n_plants // 2 :])

    # ── split time points 50/50 into train / test ──
    perm_t = rng.permutation(n_trials)
    train_trials = np.sort(perm_t[: n_trials // 2])
    test_trials = np.sort(perm_t[n_trials // 2 :])

    def _subset(samples, trials):
        return {k: v[samples][:, trials] for k, v in X.items()}

    X_disc_train = _subset(disc_idx, train_trials)
    X_disc_test = _subset(disc_idx, test_trials)
    X_val_train = _subset(val_idx, train_trials)
    X_val_test = _subset(val_idx, test_trials)

    # ── build X_eval: small subset of discover train for fingerprinting ──
    eval_samples = np.sort(
        rng.choice(disc_idx, min(n_eval_samples, len(disc_idx)), replace=False)
    )
    eval_pos = np.searchsorted(disc_idx, eval_samples)
    X_eval = {k: v[eval_pos] for k, v in X_disc_train.items()}

    # Position of each eval sample within disc_idx, for param matching in scoring
    X_eval["_sample_indices"] = eval_pos

    return (X_disc_train, X_disc_test), (X_val_train, X_val_test), X_eval


def apply_model(model_fn, data, params):
    """Vmaps `model_fn` over plants, passing in the fixed sub-component functions.

    Args:
        model_fn: Per-plant model with signature
            `model_fn(data, params, components)`.
        data (dict): Arrays with a leading plant axis, e.g. `data["L"]` of shape
            `(n_samples, n_trials)`.
        params (dict): Parameter pytree whose leaves have a leading plant axis.

    Returns:
        JAX array: Predicted growth rates, shape `(n_samples, n_trials)`.
    """
    components = {"g_light": g_light, "g_nitrogen": g_nitrogen}

    return jax.vmap(lambda d, p: model_fn(d, p, components))(data, params)


def loss_fn(model_output, data):
    """Per-plant mean squared error between predicted and observed growth rate.

    Args:
        model_output: Predicted growth rates, shape `(n_trials,)` or
            `(n_samples, n_trials)`.
        data (dict): Ground truth for the current split, with `data["growth_rate"]`
            matching the shape of `model_output`.

    Returns:
        JAX array: Per-plant losses, shape `(n_samples,)` (scalar if unbatched).
    """
    return jnp.mean((data["growth_rate"] - model_output) ** 2, axis=-1)
